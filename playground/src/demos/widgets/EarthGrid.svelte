<script>
// =============================================================================
// 地球网格组件
// -----------------------------------------------------------------------------
// 展示地球表面的经纬度网格线。
// 关键 API:
//   - Daisy.EarthGridLayers : 添加地球经纬度网格
//   - engine.camera.flyToTarget(): 飞行到目标位置
// =============================================================================

// ── 1. 组件属性 ────────────────────────────────────────────────────────────────
let { engine, daisy: Daisy, container, log: __log, registerCleanup } = $props();

// ── 2. 添加地球网格 ──────────────────────────────────────────────────────────
// 在地球表面显示经纬度网格线
engine.addWidget(new Daisy.EarthGridLayers());
__log("EarthGridLayers added");

// ── 3. 相机定位 ──────────────────────────────────────────────────────────────
// 飞行到北京上空，高度5000公里，查看网格效果
engine.camera.flyToTarget(Daisy.Cartesian3.fromDegrees(116, 40, 5000000));
</script>
